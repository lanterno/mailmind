"""What Compose needs from outside it. Each is bound in mailmind.bootstrap.compose."""
from typing import Any, Protocol


class Transport(Protocol):
    """The wire: adapters.smtp."""
    def send(self, acct: dict, raw: bytes, envelope: list, before_dot=None) -> Any: ...
    def permanent(self, e: Exception) -> bool: ...
    def sanitize_error(self, e: Exception) -> str: ...


class Copies(Protocol):
    """The copies kept on the mail server, in the Mailbox."""
    def append_to_sent(self, acct: dict, raw: bytes, message_id=None) -> str: ...
    def in_sent(self, acct: dict, message_id: str) -> bool: ...
    def append_to_drafts(self, acct: dict, raw: bytes, prev_uid=None, prev_uidvalidity=None, prev_msgid=None,
                         prev_folder=None, message_id=None, tried=None) -> Any: ...
    def delete_draft_uid(self, acct: dict, folder: str, uid, uidvalidity=None) -> bool: ...
    def delete_left_copy(self, acct: dict, message_id: str) -> Any: ...
    def probe(self, acct: dict, folder: str, uid: int, timeout: int) -> Any: ...


class Accounts(Protocol):
    """An account as the configuration has it, until Accounts holds it."""
    def get(self, email: str) -> dict: ...
    def saves_sent(self, acct: dict) -> bool: ...


class Messages(Protocol):
    """A message's row and its body, until the Mailbox holds them."""
    def original(self, pk, account=None, message_id=None) -> Any: ...
    def message(self, pk: int) -> Any: ...
    def by_msgid(self, account: str, message_id: str) -> Any: ...
    def body(self, pk: int) -> Any: ...
    def uidvalidity(self, account: str, folder: str) -> Any: ...
    def remove(self, pk: int) -> Any: ...
    def remove_copies(self, c, account: str, folder: str, uids: list) -> Any: ...
    def fetch_body(self, pk: int) -> Any: ...
    def sync_whole(self, acct: dict, folder: str) -> Any: ...
    def unreachable(self) -> tuple: ...


class Effects(Protocol):
    """What a delivered send sets off elsewhere: \\Answered on the original, and a follow-up."""
    def account_of(self, pk) -> Any: ...
    def mark_answered(self, pk, account, message_id) -> Any: ...
    def followup_sent(self, c, account: str, thread_id: str, pk, now: int, at: str) -> Any: ...


class Screen(Protocol):
    """What the server keeps about folders and tells the page, until the Mailbox and the routers hold it."""
    def names_drafts(self, folder: str) -> bool: ...
    def plays_drafts(self, account: str, folder: str) -> bool: ...
    def quiet_error(self, e: Exception) -> str: ...
    def touched(self, account: str, folder: str) -> Any: ...
    def list_changed(self, account: str, folder: str) -> Any: ...
    def stats_changed(self) -> Any: ...
