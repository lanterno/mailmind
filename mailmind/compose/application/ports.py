"""What Compose needs from outside it. Each is bound in mailmind.bootstrap.compose."""
from collections.abc import Callable, Mapping
from typing import Any, Protocol

from mailmind.content.mime import Parsed
from mailmind.kernel.row import Connection, Row

type Account = dict[str, Any]     # an account as the configuration has it, whose fields are the file's word for them


class Transport(Protocol):
    """The wire: adapters.smtp."""
    def send(self, acct: Account, raw: bytes, envelope: list[str], before_dot: Callable[[], object] | None = None) -> object: ...
    def permanent(self, e: Exception) -> bool: ...
    def sanitize_error(self, e: Exception) -> str: ...


class Copies(Protocol):
    """The copies kept on the mail server, in the Mailbox."""
    def append_to_sent(self, acct: Account, raw: bytes, message_id: str | None = None) -> str: ...
    def in_sent(self, acct: Account, message_id: str) -> bool: ...
    def append_to_drafts(self, acct: Account, raw: bytes, prev_uid: int | None = None, prev_uidvalidity: int | None = None,
                         prev_msgid: str | None = None, prev_folder: str | None = None, message_id: str | None = None,
                         tried: str | None = None) -> tuple[str, int | None, int | None, int | None]: ...
    def delete_draft_uid(self, acct: Account, folder: str | None, uid: int | None, uidvalidity: int | None = None) -> bool: ...
    def delete_left_copy(self, acct: Account, message_id: str) -> bool: ...
    def probe(self, acct: Account, folder: str, uid: int, timeout: int) -> tuple[int | None, bool] | None: ...


class Book(Protocol):
    """Compose's own tables, `outbox`, `drafts` and `draft_journal`: adapters.sqlite. Each call runs on the connection it's
    given and leaves the commit to its caller."""
    def connect(self) -> Connection: ...
    def outbox_insert(self, c: Connection, row: Mapping[str, Any]) -> tuple[int | None, bool]: ...
    def outbox_set(self, c: Connection, oid: int, **flags: int | str) -> None: ...
    def outbox_send_now(self, c: Connection, oid: int, now_ts: int) -> bool: ...
    def outbox_holds_draft(self, c: Connection, did: int) -> bool: ...
    def outbox_list(self, c: Connection, limit: int = 50) -> list[Row]: ...
    def outbox_get(self, c: Connection, oid: int) -> Row | None: ...
    def draft_get(self, c: Connection, did: int) -> Row | None: ...
    def draft_by_key(self, c: Connection, key: str) -> Row | None: ...
    def draft_set_key(self, c: Connection, did: int, key: str) -> None: ...
    def draft_by_msgid(self, c: Connection, account: str, message_id: str | None) -> Row | None: ...
    def draft_upsert(self, c: Connection, row: Mapping[str, Any]) -> int: ...
    def draft_set_resume(self, c: Connection, did: int, own_text: str | None, tail_text: str | None, tail_html: str | None,
                         bcc: str | None, raw_sha: str | None) -> None: ...
    def flagged_draft(self, c: Connection, account: str, folder: str, uid: int) -> bool: ...
    def draft_repoint(self, c: Connection, seen: Row, folder: str, uid: int, uidvalidity: int | None, forget: bool = False) -> bool: ...
    def draft_delete(self, c: Connection, did: int) -> None: ...
    def draft_note_save(self, c: Connection, did: int, mode: str, in_reply_to_pk: int | None, subject: str | None, version: int,
                        saved_by: str | None, updated_at: str) -> None: ...
    def draft_settle_push(self, c: Connection, did: int, account: str, folder: str, uid: int | None, message_id: str,
                          uidvalidity: int | None, pushed_at: int) -> None: ...
    def draft_quote(self, c: Connection, did: int) -> Row | None: ...
    def journal_get(self, c: Connection, did: int) -> Row | None: ...
    def journal_put(self, c: Connection, did: int, version: int, account: str, message_id: str, raw: bytes, raw_sha: str,
                    own_text: str, tail_text: str | None, tail_html: str | None, bcc: str | None, saved_at: int, due_at: int,
                    attempts: int) -> None: ...
    def journal_discard(self, c: Connection, did: int, version: int, account: str, now: int) -> None: ...
    def journal_tried(self, c: Connection, did: int, version: int, message_id: str) -> bool: ...
    def journal_settled(self, c: Connection, did: int, version: int) -> None: ...
    def journal_failed(self, c: Connection, did: int, attempts: int, due_at: int) -> None: ...
    def journal_due(self, c: Connection, now: int, soon: int) -> list[Row]: ...
    def journal_next_due(self, c: Connection, after: int, soon: int) -> int | None: ...
    def journal_overdue(self, c: Connection, before: int) -> list[Row]: ...
    def journal_move(self, c: Connection, did: int, to_did: int) -> None: ...


class Accounts(Protocol):
    """An account as the configuration has it, until Accounts holds it."""
    def get(self, email: str) -> Account: ...
    def saves_sent(self, acct: Account) -> bool: ...


class Messages(Protocol):
    """A message's row and its body, until the Mailbox holds them."""
    def original(self, pk: int | None, account: str | None = None, message_id: str | None = None) -> Row | None: ...
    def message(self, pk: int) -> Row | None: ...
    def by_msgid(self, account: str, message_id: str | None) -> Row | None: ...
    def body(self, pk: int) -> bytes | None: ...
    def uidvalidity(self, account: str, folder: str) -> int | None: ...
    def remove(self, pk: int) -> None: ...
    def remove_copies(self, c: Connection, account: str, folder: str, uids: list[int]) -> None: ...
    def fetch_body(self, pk: int) -> Parsed | None: ...
    def sync_whole(self, acct: Account, folder: str) -> object: ...
    def unreachable(self) -> tuple[type[Exception], ...]: ...


class Effects(Protocol):
    """What a delivered send sets off elsewhere: \\Answered on the original, and a follow-up."""
    def account_of(self, pk: int | None) -> str | None: ...
    def mark_answered(self, pk: int | None, account: str | None, message_id: str | None) -> object: ...
    def followup_sent(self, c: Connection, account: str, thread_id: str, pk: int | None, now: int, at: str) -> None: ...


class Screen(Protocol):
    """What the server keeps about folders and tells the page, until the Mailbox and the routers hold it."""
    def names_drafts(self, folder: str) -> bool: ...
    def plays_drafts(self, account: str, folder: str) -> bool: ...
    def quiet_error(self, e: Exception) -> str: ...
    def touched(self, account: str, folder: str) -> None: ...
    def list_changed(self, account: str, folder: str) -> None: ...
    def outbox_changed(self) -> None: ...
    def stats_changed(self) -> None: ...
