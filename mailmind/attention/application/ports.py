"""What Attention needs from outside it. Each is bound in mailmind.bootstrap.attention."""
from typing import Any, Protocol

from mailmind.kernel.ids import AccountId, FolderName, MessageKey, Pk, ThreadRef
from mailmind.kernel.row import Row


class AttentionBook(Protocol):
    """Snoozes, mutes and follow-ups. See adapters.sqlite, whose functions take the connection a unit of work's block
    gives. To a use case that connection is only something to pass back, hence `object`."""
    def thread_pks(self, c: object, account: AccountId, thread_id: ThreadRef) -> list[Pk]: ...
    def set_snooze(self, c: object, pk: Pk, until: int) -> None: ...
    def clear_snooze(self, c: object, pk: Pk) -> None: ...
    def due_snoozes(self, c: object, now_ts: int) -> list[Row]: ...
    def mute_thread(self, c: object, account: AccountId, thread_id: ThreadRef, when: str) -> None: ...
    def unmute_thread(self, c: object, account: AccountId, thread_id: ThreadRef) -> None: ...
    def is_muted(self, c: object, account: AccountId, thread_id: ThreadRef) -> bool: ...
    def a_member(self, c: object, account: AccountId, thread_id: ThreadRef) -> Row | None: ...

    def unread_in_thread(self, c: object, account: AccountId, thread_id: ThreadRef) -> list[Row]: ...
    def unread_in_muted_threads(self, c: object, account: AccountId) -> list[Row]: ...
    def followup_promote_due(self, c: object, now_ts: int, days: int) -> None: ...
    def followup_detect_received(self, c: object, now_ts: int, days: int, max_age_days: int) -> None: ...
    def resolve_followups(self, c: object, account: AccountId) -> None: ...
    def set_replylater(self, c: object, account: AccountId, thread_id: ThreadRef, when: str) -> None: ...
    def clear_replylater(self, c: object, account: AccountId, thread_id: ThreadRef) -> None: ...
    def dismiss_followup(self, c: object, account: AccountId, thread_id: ThreadRef, when: str) -> None: ...
    def expire_followups(self, c: object, now_ts: int, days: int) -> None: ...
    def due_followup_keys(self, c: object) -> set[tuple[str, str]]: ...


class Messages(Protocol):
    """What only the Mailbox may do to a message's row. `queue_flags` is the SetFlags port: the change reaches the
    server through the queue, in the same transaction, and `flags_queued`, once that has committed, wakes the queue."""
    def get(self, c: object, pk: Pk) -> Row | None: ...
    def queue_flags(self, c: object, row: Row, flags: dict[str, bool], mutation_id: str, when: str) -> bool: ...
    def flags_queued(self) -> None: ...
    def copy_in_folder(self, c: object, key: MessageKey, folder: FolderName) -> Pk | None: ...
    def set_local_flags(self, c: object, pk: Pk, **flags: int) -> object: ...
    def index(self, c: object, pk: Pk) -> object: ...


class Accounts(Protocol):
    def emails(self) -> list[AccountId]: ...


class Undo(Protocol):
    def push(self, entry: dict[str, Any], group: str | None) -> None: ...
