"""What Curation needs from outside it. Each is bound in mailmind.bootstrap.curation."""
from collections.abc import Callable, Collection, Iterable, Sequence
from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Protocol, TypedDict

from mailmind.content.mime import UnsubWay
from mailmind.curation.domain.live import Audited, LiveMail
from mailmind.curation.domain.rulebook import RuleSets, Rules
from mailmind.kernel.row import Row


class Headers(Protocol):
    """One message's header fields, as a fetch got them."""
    @property
    def uid(self) -> int: ...
    @property
    def raw(self) -> bytes: ...
    @property
    def internaldate(self) -> datetime | None: ...


class LiveSession(Protocol):
    """A connection to an account's server, as far as a sweep or expiry reads through it. A refusal raises
    imaplib's IMAP4.error, a lost connection IMAP4.abort."""
    def select(self, folder: str) -> object: ...
    def uids(self, *criteria: str) -> list[int]: ...
    def headers(self, uids: Collection[int], fields: Iterable[str], *, internaldate: bool = False) -> Sequence[Headers]: ...
    def logout(self) -> None: ...


class SenderAccount(TypedDict):
    """An account a sender wrote to, and how often."""
    email: str
    count: int


class RuleBookRepository(Protocol):
    """The rule book's one reader and writer."""
    def load(self) -> Rules: ...
    def sets(self) -> RuleSets: ...
    def add(self, token: str, verdict: str) -> tuple[str, str]: ...
    def remove(self, token: str) -> None: ...
    def change[T](self, apply: Callable[[Rules], T]) -> T: ...


class Conditions(Protocol):
    """A search read as a condition on one message: Discovery's grammar and its index."""
    def refusal(self, q: str) -> str | None: ...
    def holds(self, c: object, pk: int, q: str) -> bool: ...


class SafeHttp(Protocol):
    """The one request MailMind makes to an address a message named."""
    def one_click_post(self, url: str) -> tuple[bool, int, str]: ...


class AuditLog(Protocol):
    """A reviewable record of what was trashed. Written before a move, so a crash still records it."""
    def swept(self, account: str, rows: Sequence[Audited]) -> None: ...
    def cleaned_up(self, from_addr: str, token: str, swept: int, status: str) -> None: ...


class SystemSend(Protocol):
    """A message MailMind sends for itself, from one of the person's accounts. `key` makes a second try the same send."""
    def send(self, account: str, raw: bytes, message_id: str, to: str, subject: str, key: str) -> None: ...


class SenderMail(Protocol):
    """Stored mail by sender and folder, and Curation's own tables. See adapters.sqlite."""
    def noisy_senders(self, buckets: list[str], min_count: int) -> list[Row]: ...
    def accounts_by_sender(self, addrs: list[str]) -> dict[str, list[SenderAccount]]: ...
    def counts(self, addr: str) -> tuple[int, int]: ...
    def sweep_targets(self, from_addr: str, limit: int) -> list[Row]: ...
    def unsub_stored(self, from_addr: str) -> tuple[list[Row], list[str], UnsubWay | None]: ...
    def remember_unsub(self, pk: int, parsed: UnsubWay) -> None: ...
    def keep_unsub(self, from_addr: str, info: UnsubWay, accounts: list[str]) -> None: ...
    def kept_unsub(self, from_addr: str) -> Row | None: ...
    def attempt(self, key: str) -> Row | None: ...
    def record_attempt(self, from_addr: str, method: str, status: str, http_status: int | None, key: str,
                       accounts: list[str]) -> None: ...
    def inbox_senders(self, account: str) -> list[Row]: ...
    def stored_inbox(self, account: str) -> list[Row]: ...
    def stored_junk_ids(self, account: str) -> set[str]: ...
    def forget_moved(self, account: str, moved: Sequence[LiveMail], stragglers: Iterable[str]) -> None: ...
    def forget_expired(self, account: str, targets: Sequence[LiveMail], stragglers: Iterable[str]) -> None: ...


class ListHeaders(Protocol):
    """Ask the server for one stored message's unsubscribe headers alone."""
    def read(self, r: Row) -> bytes | None: ...


class FilingCommands(Protocol):
    """What Curation asks of the Mailbox: file a message, and say that stored mail changed."""
    def trash(self, pk: int, undo_group: str) -> dict[str, Any]: ...
    def trash_now(self, pk: int) -> bool: ...
    def trash_many(self, rows: Sequence[dict[str, Any]], undo_group: str) -> dict[str, Any]: ...
    def undo_push(self, descriptor: dict[str, Any], group: str) -> None: ...
    def reclassify(self, token: str) -> int: ...
    def stats_changed(self) -> None: ...
    def folders_changed(self, account: str, moved: int) -> None: ...


class Mailboxes(Protocol):
    """The accounts, and a connection to each, for what has to read the live server."""
    def all(self) -> list[dict[str, Any]]: ...
    def get(self, email: str) -> dict[str, Any]: ...
    def known(self) -> set[str]: ...
    def preload_creds(self) -> None: ...
    def open_session(self, acct: dict[str, Any]) -> LiveSession: ...
    def borrow(self, acct: dict[str, Any]) -> AbstractContextManager[LiveSession]: ...
    def trash_folder(self, acct: dict[str, Any]) -> str: ...
    def quote(self, value: str) -> str: ...
    def move_verified(self, session: LiveSession, uids: list[str], dest: str) -> tuple[int, list[str]]: ...
