"""What Curation needs from outside it. Each is bound in mailmind.bootstrap.curation."""
from typing import Any, Protocol


class RuleBookRepository(Protocol):
    """The rule book's one reader and writer."""
    def load(self) -> dict: ...
    def sets(self) -> dict: ...
    def add(self, token: str, verdict: str) -> tuple[str, str]: ...
    def remove(self, token: str) -> None: ...


class SafeHttp(Protocol):
    """The one request MailMind makes to an address a message named."""
    def one_click_post(self, url: str) -> tuple[bool, int, str]: ...


class AuditLog(Protocol):
    """A reviewable record of what was trashed. Written before a move, so a crash still records it."""
    def swept(self, account: str, rows: list) -> None: ...
    def cleaned_up(self, from_addr: str, token: str, swept: int, status: str) -> None: ...


class SystemSend(Protocol):
    """A message MailMind sends for itself, from one of the person's accounts."""
    def send(self, account: str, raw: bytes, recipients: list) -> bool: ...


class SenderMail(Protocol):
    """Stored mail by sender and folder, and Curation's own tables. See adapters.sqlite."""
    def noisy_senders(self, buckets: list, min_count: int) -> list: ...
    def accounts_by_sender(self, addrs: list) -> dict: ...
    def subjects_by_sender(self, addrs: list, keep: int) -> dict: ...
    def counts(self, addr: str) -> tuple[int, int]: ...
    def sweep_targets(self, from_addr: str, limit: int) -> list: ...
    def unsub_stored(self, from_addr: str) -> tuple: ...
    def remember_unsub(self, pk: int, parsed: dict) -> None: ...
    def keep_unsub(self, from_addr: str, info: dict, accounts: list) -> None: ...
    def kept_unsub(self, from_addr: str) -> Any: ...
    def attempt(self, key: str) -> Any: ...
    def record_attempt(self, from_addr: str, method: str, status: str, http_status, key: str, accounts: list) -> None: ...
    def inbox_senders(self, account: str) -> list: ...
    def stored_inbox(self, account: str) -> list: ...
    def ai_junk_ids(self, account: str) -> set: ...
    def forget_moved(self, account: str, moved: list, stragglers) -> None: ...
    def forget_expired(self, account: str, targets: list, stragglers) -> None: ...


class ListHeaders(Protocol):
    """Ask the server for one stored message's unsubscribe headers alone."""
    def read(self, r) -> bytes | None: ...


class FilingCommands(Protocol):
    """What Curation asks of the Mailbox: file a message, and say that stored mail changed."""
    def trash(self, pk: int, undo_group: str) -> dict: ...
    def trash_now(self, pk: int) -> bool: ...
    def undo_push(self, descriptor: dict, group: str) -> None: ...
    def reclassify(self, token: str) -> int: ...
    def stats_changed(self) -> None: ...
    def folders_changed(self, account: str, moved: int) -> None: ...


class Mailboxes(Protocol):
    """The accounts, and a connection to each, for what has to read the live server."""
    def all(self) -> list: ...
    def get(self, email: str) -> dict: ...
    def known(self) -> set: ...
    def preload_creds(self) -> None: ...
    def open_session(self, acct: dict) -> Any: ...
    def borrow(self, acct: dict) -> Any: ...
    def trash_folder(self, acct: dict) -> str: ...
    def quote(self, value: str) -> str: ...
    def move_verified(self, session, uids: list, dest: str) -> tuple[int, list]: ...
