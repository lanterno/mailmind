"""What Calendar needs from outside it. Each is bound in mailmind.bootstrap.calendar."""
from collections.abc import Iterator, Mapping
from datetime import datetime
from typing import Any, Protocol

from mailmind.calendar.domain.invite import Invite
from mailmind.kernel.row import Row


class IcsReader(Protocol):
    """An invite's text as a display-ready dict, and when it next happens."""
    def parse(self, text: str) -> Invite | None: ...
    def next_occurrence(self, inv: Invite, after: datetime) -> tuple[datetime, datetime] | None: ...


class StoredInvites(Protocol):
    """Invite parts in stored bodies, never IMAP, and what the outbox has sent. See adapters.sqlite."""
    def invite_parts(self, since: int, account: str | None, skipped_roles: tuple[str, ...]) -> Iterator[tuple[Row, str]]: ...
    def body(self, pk: int) -> bytes | None: ...
    def keys_sent(self, prefix: str) -> list[str]: ...


class Messages(Protocol):
    """What an RSVP needs of a message and its account, until the Mailbox and Accounts hold them."""
    def message(self, pk: int) -> Row | None: ...
    def account(self, email: str) -> dict[str, Any]: ...
    def fetched(self, account: str, pk: int) -> Mapping[str, Any]: ...
    def quiet_error(self, e: Exception) -> str: ...


class SystemSend(Protocol):
    """A message MailMind sends for itself: built, then through the outbox under an idempotency key."""
    def build(self, spec: dict[str, Any], original: Row) -> Mapping[str, Any]: ...
    def enqueue(self, built: Mapping[str, Any], meta: dict[str, Any]) -> tuple[int | None, bool]: ...
