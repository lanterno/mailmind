"""What the Mailbox needs of the rest. The mail on a server goes through session.MailSession, its own port."""
from typing import Protocol


class Accounts(Protocol):
    def get(self, email): ...

    def accounts(self): ...

    def trash_folder(self, acct): ...

    def profile(self, acct): ...

    def preload_creds(self): ...


class Classifier(Protocol):
    """Curation decides, as ingest reads each message, what it is and so whether its body is fetched."""
    def classify(self, addr, subject, name, has_unsub): ...

    def is_junk(self, bucket): ...

    def by_rule(self, reason): ...

    def plan_stored(self, acct): ...

    def buckets(self): ...


class Attention(Protocol):
    """What new mail means for what is waiting: a muted thread's new member, a follow-up answered."""
    def on_ingest(self, c, account): ...

    def resolve_followups(self, c, account): ...

    def muted_count(self, c, account): ...

    def waiting_count(self, c, account): ...

    def replylater_count(self, c, account): ...

    def list_muted(self, c, account): ...

    def list_waiting(self, c, account): ...

    def list_replylater(self, c, account): ...

    def wake_due(self): ...


class Reader(Protocol):
    """What another context adds to a message as it opens."""
    def invite_of(self, pk, parsed): ...

    def draft_info(self, row): ...


class Index(Protocol):
    def index_message(self, c, pk): ...


class StoredMail(Protocol):
    """mailmind.mailbox.adapters.sqlite: the rows of the mail, the folders and the queue."""
    RECIPIENTS_CHARS: int

    def _recipients_of(self, parsed): ...

    def conn(self): ...

    def delete_message(self, c, pk): ...

    def fts_set_body(self, c, pk, body_text): ...

    def get_body(self, c, pk): ...

    def get_message(self, c, pk): ...

    def get_message_by_msgid(self, c, account, message_id): ...

    def get_modseq(self, c, account, folder): ...

    def get_scan_state(self, c, account, folder): ...

    def get_uidvalidity(self, c, account, folder='INBOX'): ...

    def get_watermark(self, c, account, folder='INBOX'): ...

    def mark_pending_removal(self, c, pk, mutation_id): ...

    def pending_removal_pks(self, c, mutation_id): ...

    def queue_flags(self, c, row, flags, mutation_id, when): ...

    def read_mut_get(self, c, mid): ...

    def read_mut_insert(self, c, row): ...

    def read_mut_latest_by_msgid(self, c, account, message_id): ...

    def read_mut_open(self, c, limit): ...

    def read_mut_open_counts(self, c): ...

    def read_mut_set_dest(self, c, mid, dest): ...

    def read_mut_set_payload(self, c, mid, payload): ...

    def recompute_threads(self, c, account): ...

    def reconcile(self, c, account, folder, live_uids, when, among=None): ...

    def reset_folder(self, c, account, folder): ...

    def restore_pending(self, c, mutation_id): ...

    def set_list_unsub(self, c, pk, raw, method): ...

    def set_local_flags(self, c, pk, **flags): ...

    def set_modseq(self, c, account, folder, modseq): ...

    def set_recipients(self, c, pk, addrs): ...

    def set_scan_state(self, c, account, folder, state): ...

    def set_uidvalidity(self, c, account, folder, uidvalidity): ...

    def set_watermark(self, c, account, last_uid, last_sync, folder='INBOX'): ...

    def store_body(self, c, pk, raw, when): ...

    def undo_entries(self, c): ...

    def undo_forget_move(self, c, account, message_id, src_folder): ...

    def undo_pop(self, c): ...

    def undo_push(self, c, entry, group, keep): ...

    def undo_put_back(self, c, entry): ...

    def upsert_message(self, c, m): ...
