class Pruned(TypedDict):
    """What reconcile found in one folder."""
    account: str
    live: int
    stored: int
    ghosts: int
    pruned: int
    error: str | None


class AccountPruned(Pruned):
    """What it came to over an account's folders."""
    folders: int
