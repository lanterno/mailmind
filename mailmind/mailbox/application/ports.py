"""What the Mailbox needs of the rest. The mail on a server goes through session.MailSession, its own port."""
from collections.abc import Collection, Iterable, Mapping, Sequence
from typing import Any, Protocol, TypedDict

from mailmind.content.mime import Attachment, Parsed
from mailmind.kernel.row import Connection, Row
from mailmind.mailbox.application.session import MailSession

type Account = dict[str, Any]                 # an entry of the configuration, as Accounts reads it
type Result = tuple[dict[str, Any], int]      # what a request is answered with: its JSON, and the HTTP status
type Stored = tuple[int, int, int]            # what a sync stored: kept, junk, the highest UID it saw


class OpenSession(Protocol):
    """A logged-in session on the account's server. One that can't be made raises what session.MailSession says."""
    def __call__(self, acct: Account, *, timeout: int = ...) -> MailSession: ...


class Server(Protocol):
    """What an account's server does on its own, and its quirks: Accounts' ProviderProfile."""
    @property
    def archive_is_label_removal(self) -> bool: ...
    @property
    def junk_fallback(self) -> str | None: ...
    @property
    def marks_trash_read(self) -> bool: ...
    @property
    def gmail_threads(self) -> bool: ...
    @property
    def bridge(self) -> bool: ...
    @property
    def recycle_seconds(self) -> int: ...
    @property
    def recycle_uses(self) -> int: ...


class Accounts(Protocol):
    def quiet_error(self, e: BaseException) -> str: ...

    def error_kind(self, e: BaseException) -> str: ...

    def get(self, email: str) -> Account: ...

    def accounts(self) -> list[Account]: ...

    def trash_folder(self, acct: Account) -> str: ...

    def profile(self, acct: Account) -> Server: ...

    def preload_creds(self) -> int: ...


class Directory(Accounts, Protocol):
    """What the page's first answer asks of Accounts too: who it sends as, and where a message opens on the web."""
    def deep_link(self, row: Row, wmap: Mapping[str, str | None] | None = None) -> str: ...

    def alias_map(self) -> dict[str, Any]: ...

    def webmail_map(self) -> dict[str, str | None]: ...

    def signature_map(self) -> dict[str, Any]: ...

    def signature_default(self) -> Any: ...


class Classifier(Protocol):
    """Curation decides, as ingest reads each message, what it is and so whether its body is fetched."""
    def classify(self, addr: str, subject: str, name: str, has_unsub: bool) -> tuple[str, str, str]: ...

    def is_junk(self, bucket: str) -> bool: ...

    def by_rule(self, reason: str | None) -> bool: ...

    def plan_stored(self, acct: Account) -> dict[str, Any]: ...

    def buckets(self) -> list[dict[str, Any]]: ...


class Attention(Protocol):
    """What new mail means for what is waiting: a muted thread's new member, a follow-up answered."""
    def on_ingest(self, c: Connection, account: str) -> object: ...

    def snooze(self, body: dict[str, Any]) -> Result: ...

    def resolve_followups(self, c: Connection, account: str) -> object: ...

    def muted_count(self, c: Connection, account: str) -> int: ...

    def waiting_count(self, c: Connection, account: str) -> int: ...

    def replylater_count(self, c: Connection, account: str) -> int: ...

    def list_muted(self, c: Connection, account: str) -> list[Row]: ...

    def list_waiting(self, c: Connection, account: str) -> list[Row]: ...

    def waiting_on_others(self, c: Connection, accounts: Sequence[str], limit: int) -> list[Row]: ...

    def list_replylater(self, c: Connection, account: str) -> list[Row]: ...

    def wake_due(self) -> object: ...


class Reader(Protocol):
    """What another context adds to a message as it opens."""
    def invite_of(self, pk: int, parsed: Parsed) -> tuple[object, object]: ...

    def draft_info(self, row: Row) -> Mapping[str, Any]: ...


class Index(Protocol):
    def index_message(self, c: Connection, pk: int) -> object: ...


class Listed(Row, Protocol):
    """A row that can say which columns it holds: a digest's depends on what its query found."""
    def keys(self) -> Iterable[str]: ...


