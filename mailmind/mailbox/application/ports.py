"""What the Mailbox needs of the rest. The mail on a server goes through session.MailSession, its own port."""
from typing import Any, Protocol


class Accounts(Protocol):
    def get(self, email) -> Any: ...

    def accounts(self) -> Any: ...

    def trash_folder(self, acct) -> Any: ...

    def profile(self, acct) -> Any: ...

    def preload_creds(self) -> Any: ...


class Classifier(Protocol):
    """Curation decides, as ingest reads each message, what it is and so whether its body is fetched."""
    def classify(self, addr, subject, name, has_unsub) -> Any: ...

    def is_junk(self, bucket) -> Any: ...

    def by_rule(self, reason) -> Any: ...

    def plan_stored(self, acct) -> Any: ...

    def buckets(self) -> Any: ...


class Attention(Protocol):
    """What new mail means for what is waiting: a muted thread's new member, a follow-up answered."""
    def on_ingest(self, c, account) -> Any: ...

    def snooze(self, body) -> Any: ...

    def resolve_followups(self, c, account) -> Any: ...

    def muted_count(self, c, account) -> Any: ...

    def waiting_count(self, c, account) -> Any: ...

    def replylater_count(self, c, account) -> Any: ...

    def list_muted(self, c, account) -> Any: ...

    def list_waiting(self, c, account) -> Any: ...

    def list_replylater(self, c, account) -> Any: ...

    def wake_due(self) -> Any: ...


class Reader(Protocol):
    """What another context adds to a message as it opens."""
    def invite_of(self, pk, parsed) -> Any: ...

    def draft_info(self, row) -> Any: ...


class Index(Protocol):
    def index_message(self, c, pk) -> Any: ...


class StoredMail(Protocol):
    """mailmind.mailbox.adapters.sqlite: the rows of the mail, the folders and the queue."""
    RECIPIENTS_CHARS: int

    def _recipients_of(self, parsed) -> Any: ...

    def account_health(self, c) -> Any: ...

    def clear_sync_error(self, c, account) -> Any: ...

    def conn(self) -> Any: ...

    def delete_message(self, c, pk) -> Any: ...

    def digest(self, c, min_importance=1, account=None, limit=300) -> Any: ...

    def fts_set_body(self, c, pk, body_text) -> Any: ...

    def get_body(self, c, pk) -> Any: ...

    def get_message(self, c, pk) -> Any: ...

    def get_message_by_msgid(self, c, account, message_id) -> Any: ...

    def get_modseq(self, c, account, folder) -> Any: ...

    def get_scan_state(self, c, account, folder) -> Any: ...

    def get_uidvalidity(self, c, account, folder='INBOX') -> Any: ...

    def get_watermark(self, c, account, folder='INBOX') -> Any: ...

    def mark_pending_removal(self, c, pk, mutation_id) -> Any: ...

    def pending_removal_pks(self, c, mutation_id) -> Any: ...

    def queue_flags(self, c, row, flags, mutation_id, when) -> Any: ...

    def read_mut_get(self, c, mid) -> Any: ...

    def read_mut_insert(self, c, row) -> Any: ...

    def read_mut_latest_by_msgid(self, c, account, message_id) -> Any: ...

    def read_mut_open(self, c, limit) -> Any: ...

    def read_mut_open_counts(self, c) -> Any: ...

    def read_mut_set_dest(self, c, mid, dest) -> Any: ...

    def read_mut_set_payload(self, c, mid, payload) -> Any: ...

    def recompute_threads(self, c, account) -> Any: ...

    def reconcile(self, c, account, folder, live_uids, when, among=None) -> Any: ...

    def record_sync_result(self, c, account, ok, err_name=None, kind=None, when=None) -> Any: ...

    def reset_folder(self, c, account, folder) -> Any: ...

    def restore_pending(self, c, mutation_id) -> Any: ...

    def set_list_unsub(self, c, pk, raw, method) -> Any: ...

    def set_local_flags(self, c, pk, **flags) -> Any: ...

    def set_modseq(self, c, account, folder, modseq) -> Any: ...

    def set_recipients(self, c, pk, addrs) -> Any: ...

    def set_scan_state(self, c, account, folder, state) -> Any: ...

    def set_uidvalidity(self, c, account, folder, uidvalidity) -> Any: ...

    def set_watermark(self, c, account, last_uid, last_sync, folder='INBOX') -> Any: ...

    def stats(self, c) -> Any: ...

    def store_body(self, c, pk, raw, when) -> Any: ...

    def undo_entries(self, c) -> Any: ...

    def undo_forget_move(self, c, account, message_id, src_folder) -> Any: ...

    def undo_pop(self, c) -> Any: ...

    def undo_push(self, c, entry, group, keep) -> Any: ...

    def undo_put_back(self, c, entry) -> Any: ...

    def upsert_message(self, c, m) -> Any: ...
